# ScatteringFused module
# ---------------------------------------------------------------------------
class ScatteringFused(nn.Module):
    """
    Replacement for Scattering that does the entire scattering
    pipeline using Triton kernel launches.

    Holds parameters with names compatible with the original Scattering
    class so that an existing checkpoint can be loaded directly via
    `load_state_dict`.  After loading, `reconfigure(device)` must be
    called to copy the network's weights into the
    kernels.
    """

    def __init__(self, n_channel, n_constituent, dropout_p, device):
        super().__init__()
        self.n_channel = n_channel
        self.device = device

        # Same names as in the original Scattering so that
        # the parameter keys in the state_dict line up.
        # These routines are not called in the computation
        self.direct_scattering = multiple_mlps.MultipleMLPs_I9_Triton(
            n_inputs=n_constituent + 1, n_hidden_layers=3,
            n_channels=n_channel, dropout_p=dropout_p, device=device,
            bias=True, requires_grad=False)

        self.diffuse_scattering = multiple_mlps.MultipleMLPs_I8_Triton(
            n_inputs=n_constituent, n_hidden_layers=3,
            n_channels=n_channel, dropout_p=dropout_p, device=device,
            bias=True, requires_grad=False)

        # Per-channel selection weights, kept as Conv2d so that the
        # checkpoint key `direct_selection.weight` /
        # `diffuse_selection.weight` matches.  The Conv2d is never
        # actually called in the computation.
        self.direct_selection = nn.Conv2d(
            in_channels=n_channel, out_channels=n_channel,
            kernel_size=(8, 1), stride=(1, 1), padding=0, dilation=1,
            groups=n_channel, bias=False, device=device)

        self.diffuse_selection = nn.Conv2d(
            in_channels=n_channel, out_channels=n_channel,
            kernel_size=(8, 1), stride=(1, 1), padding=0, dilation=1,
            groups=n_channel, bias=False, device=device)

    def reset_dropout(self, dropout_p):
        self.direct_scattering.reset_dropout(dropout_p)
        self.diffuse_scattering.reset_dropout(dropout_p)

    def reconfigure(self, device):
        # Copy weights from original model to optimized model
        
        # Materialize "Multiple MLP" weight buffers (W0/B0/Wh0/Bh0/Wh1/Bh1/Wo/Bo)
        self.direct_scattering.reconfigure(device=device)
        self.diffuse_scattering.reconfigure(device=device)

        # Cache contiguous flat selection weight tensors of shape
        # [n_channel, 8].  The Conv2d weight has shape
        # [n_channel, 1, 8, 1] which is already contiguous, so the
        # reshape is a free view.
        with torch.no_grad():
            self.register_buffer(
                'wsel_direct',
                self.direct_selection.weight.detach()
                    .reshape(self.n_channel, 8).contiguous())
            self.register_buffer(
                'wsel_diffuse',
                self.diffuse_selection.weight.detach()
                    .reshape(self.n_channel, 8).contiguous())

            # Pre-store hidden/output weights as FP16 for T4 tensor cores.
            # Avoids in-kernel FP32->FP16 conversion, reducing shared memory
            # footprint and register pressure.
            for mlp in (self.direct_scattering, self.diffuse_scattering):
                mlp.register_buffer('wh0_f16', mlp.wh0.to(torch.float16).contiguous())
                mlp.register_buffer('wh1_f16', mlp.wh1.to(torch.float16).contiguous())
                mlp.register_buffer('wo_f16',  mlp.wo.to(torch.float16).contiguous())

                # Block-diagonal FP16 storage for the "_bd" kernel variant.
                # Hidden layers are [32,32] block-diagonal with 4 blocks of 8x8.
                # Triton on SM75 requires K>=16 for tl.dot, so we PAIR two
                # 8x8 blocks into a single [16,16] block-diagonal matrix and
                # process two [BLOCK_B,16] x [16,16] matmuls per layer (50%
                # sparse per matmul, but that's still 2x fewer FMAs than one
                # dense [BLOCK_B,32] x [32,32] — which is 75% sparse).
                # Storage: [2, 16, 16] FP16 = two paired slices of the dense
                # [32,32] matrix: [:16,:16] (blocks 0&1) and [16:,16:] (blocks 2&3).
                wh0_pair = torch.stack([
                    mlp.wh0[:16, :16].to(torch.float16),
                    mlp.wh0[16:, 16:].to(torch.float16),
                ], dim=0)
                wh1_pair = torch.stack([
                    mlp.wh1[:16, :16].to(torch.float16),
                    mlp.wh1[16:, 16:].to(torch.float16),
                ], dim=0)
                mlp.register_buffer('wh0_f16_bd', wh0_pair.contiguous())
                mlp.register_buffer('wh1_f16_bd', wh1_pair.contiguous())

                # Split-path (v2) buffers: input and output layers also
                # pre-packed as [2, 16, 16] for the reshape-free BD kernel.
                # Input w0 [16, 32] FP32 → two [16, 16] halves (left/right cols)
                w0_pair = torch.stack([
                    mlp.w0[:, :16],
                    mlp.w0[:, 16:],
                ], dim=0)
                mlp.register_buffer('w0_bd', w0_pair.contiguous())
                # Output wo [32, 32] FP16 → two [16, 16] diagonal blocks
                wo_pair = torch.stack([
                    mlp.wo[:16, :16].to(torch.float16),
                    mlp.wo[16:, 16:].to(torch.float16),
                ], dim=0)
                mlp.register_buffer('wo_f16_bd', wo_pair.contiguous())

    def forward(self, mass_flat, ke_flat, w_eff_filter, mu_dir_flat,
                inv_mu_diffuse_scalar, n_examples, n_layers):
        """Scattering computation

        Inputs (all already on device, all already flattened over the
        sample-layer axis where applicable):
            mass_flat            : [B, 8]              (B = n_examples*n_layers)
            ke_flat              : [B, 6]
            w_eff_filter         : [n_channels, 8]
            mu_dir_flat          : [B]
            inv_mu_diffuse_scalar: Python float
            n_examples, n_layers : ints, used only to view outputs

        Returns the 8 per-layer radiative quantities expected by
        MultiReflectionFast, each shaped [n_examples, n_layers, n_channels].
        """
        n_channels = self.n_channel
        B = mass_flat.shape[0]

        # Output buffers — flat 2D, viewed as 3D for downstream consumers.
        t_full_direct  = torch.empty((B, n_channels), device=self.device, dtype=torch.float32)
        e_t_direct     = torch.empty_like(t_full_direct)
        e_r_direct     = torch.empty_like(t_full_direct)
        e_a_direct     = torch.empty_like(t_full_direct)

        t_full_diffuse = torch.empty_like(t_full_direct)
        e_t_diffuse    = torch.empty_like(t_full_direct)
        e_r_diffuse    = torch.empty_like(t_full_direct)
        e_a_diffuse    = torch.empty_like(t_full_direct)

        # Methods that use block diagonal structure (BD) of scattering
        # algorithm
        if USE_BD_V2_COMBINED_SCATTERING:
            # Puts all computation (direct and diffuse, left and right blocks)
            # together in a single kernels. Avoids some duplicated computation.
            # However, isn't faster for T4 GPU probably because of register
            # spilling and oversubscribed L1 Cache. Needs testing on other
            # GPUs
            _launch = fused_scattering.launch_optical_scattering_combined_bd_v2
        elif USE_BD_V2_SPLIT_SCATTERING:
            # Split into separate kernels for "left" and "right"
            # matric blocks for both direct and diffuse radiation.
            # Total of 4 kernels
            # Goal was to reduce pressure on registers but incurs additional I/O
            # to global memory that is very costly
            _launch = fused_scattering.launch_optical_scattering_bd_v2_split
        elif USE_BD_V2_SCATTERING:
            # Split into separate kernels for direct and diffuse radiation
            # Same as fused_scattering.launch_optical_scattering_bd,
            # except removes unneccessary split, transpose, join operations
            # So far this gives the best performance
            _launch = fused_scattering.launch_optical_scattering_bd_v2
        elif USE_BD_SCATTERING:
            # Split into separate kernels for direct and diffuse radiation
            # Does unnecessary split, transpose, and join operations in handling
            # block diagonal matrix 
            # Initially generated by Claude Code
            _launch = fused_scattering.launch_optical_scattering_bd
        else:
            # Does not take advantage of block diagonal matrix multiply
            _launch = fused_scattering.launch_optical_scattering
        _launch(
            mass_flat, ke_flat, w_eff_filter, mu_dir_flat,
            inv_mu_diffuse_scalar,
            self.direct_scattering, self.diffuse_scattering,
            self.wsel_direct, self.wsel_diffuse,
            t_full_direct,  e_t_direct,  e_r_direct,  e_a_direct,
            t_full_diffuse, e_t_diffuse, e_r_diffuse, e_a_diffuse,
            n_channels)

        return [
            t_full_direct .view(n_examples, n_layers, n_channels),
            t_full_diffuse.view(n_examples, n_layers, n_channels),
            e_t_direct    .view(n_examples, n_layers, n_channels),
            e_r_direct    .view(n_examples, n_layers, n_channels),
            e_a_direct    .view(n_examples, n_layers, n_channels),
            e_t_diffuse   .view(n_examples, n_layers, n_channels),
            e_r_diffuse   .view(n_examples, n_layers, n_channels),
            e_a_diffuse   .view(n_examples, n_layers, n_channels),
        ]

    # Fused optical depth with scattering into single kernel
    # Slower on T4 than separate kernels for optical depth and scattering
    def forward_fke(self, mass_flat, tp_flat, w_eff_filter, mu_dir_flat,
                    inv_mu_diffuse_scalar, ke_weights, n_examples, n_layers):
        """Fused ke+scattering: computes ke inline from temperature/pressure."""
        n_channels = self.n_channel
        B = mass_flat.shape[0]

        t_full_direct  = torch.empty((B, n_channels), device=self.device, dtype=torch.float32)
        e_t_direct     = torch.empty_like(t_full_direct)
        e_r_direct     = torch.empty_like(t_full_direct)
        e_a_direct     = torch.empty_like(t_full_direct)

        t_full_diffuse = torch.empty_like(t_full_direct)
        e_t_diffuse    = torch.empty_like(t_full_direct)
        e_r_diffuse    = torch.empty_like(t_full_direct)
        e_a_diffuse    = torch.empty_like(t_full_direct)

        fused_scattering.launch_optical_scattering_fke(
            mass_flat, tp_flat, w_eff_filter, mu_dir_flat,
            inv_mu_diffuse_scalar,
            ke_weights,
            self.direct_scattering, self.diffuse_scattering,
            self.wsel_direct, self.wsel_diffuse,
            t_full_direct,  e_t_direct,  e_r_direct,  e_a_direct,
            t_full_diffuse, e_t_diffuse, e_r_diffuse, e_a_diffuse,
            n_channels)

        return [
            t_full_direct .view(n_examples, n_layers, n_channels),
            t_full_diffuse.view(n_examples, n_layers, n_channels),
            e_t_direct    .view(n_examples, n_layers, n_channels),
            e_r_direct    .view(n_examples, n_layers, n_channels),
            e_a_direct    .view(n_examples, n_layers, n_channels),
            e_t_diffuse   .view(n_examples, n_layers, n_channels),
            e_r_diffuse   .view(n_examples, n_layers, n_channels),
            e_a_diffuse   .view(n_examples, n_layers, n_channels),
        ]


