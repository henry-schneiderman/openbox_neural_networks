# FullNetV3 — orchestrates optical depth, scattering, multireflection, propagation.
# ---------------------------------------------------------------------------
class FullNetV3(nn.Module):
    """Inference-only top-level network.

    State-dict compatible with the original version.  Names
    must therefore line up exactly:

        mu_diffuse_net, spectral_net,
        optical_depth_net.module.<...>,
        scattering_net.<direct|diffuse>_scattering.<...>,
        scattering_net.<direct|diffuse>_selection.weight

    Notably, the original version wraps the scattering module inside a
    `LayerDistributed`, so its state_dict keys begin with
    `scattering_net.module.`.  We therefore wrap our ScatteringFused
    in a thin pass-through `_ScatteringHolder` whose attribute name is
    `module`, in order to keep the keys identical.
    """

    class _ScatteringHolder(nn.Module):
        def __init__(self, inner):
            super().__init__()
            self.module = inner

    def __init__(self, n_channel, n_constituent, dropout_p, device):
        super().__init__()
        with torch.no_grad():
            self.device = device
            self.n_channel = n_channel
            self.solar_constant = 1361.0

            self.mu_diffuse_net = nn.Linear(1, 1, bias=False, device=device)
            torch.nn.init.uniform_(self.mu_diffuse_net.weight, a=0.4, b=0.6)

            self.spectral_net = nn.Linear(1, n_channel, bias=False, device=device)
            torch.nn.init.uniform_(self.spectral_net.weight, a=0.4, b=0.6)

            # OpticalDepth: keep the original PyTorch module 
            # (it is `torch.compile`-decorated
            self.optical_depth_net = tn.LayerDistributed(
                tn.OpticalDepth(n_channel, dropout_p, device))

            # Scattering: fused replacement.  Wrap in a holder so that
            # the state_dict keys read `scattering_net.module.<...>`.
            self.scattering_net = FullNetV3._ScatteringHolder(
                ScatteringFused(n_channel, n_constituent, dropout_p, device))

            # Multireflection: fused Triton kernel.
            self.multireflection_net = multireflection_timing.MultiReflectionFast(device)

            # Propagation: fused Triton kernel.
            self.propagation_net = fused_propagation.PropagationFused(n_channel)

            # Fused multireflection + propagation (optional, behind env var)
            if USE_FUSED_MULTIREF_PROP:
                self.fused_multiref_prop = (
                    fused_multireflection_propagation
                    .MultiReflectionPropagationFused(n_channel, device))

    def reset_dropout(self, dropout_p):
        self.optical_depth_net.reset_dropout(dropout_p)
        self.scattering_net.module.reset_dropout(dropout_p)

    def reconfigure(self, device):
        """
        Copies weights from original model to optimized model.

        Must be called once after `load_state_dict`.
        """
        self.scattering_net.module.reconfigure(device=device)

        # Pre-compute scalars / per-channel constants that depend only
        # on parameters, not on inputs, so that the forward pass does
        # not have to recompute them per batch.
        with torch.no_grad():
            one = torch.ones((1,), dtype=torch.float32, device=self.device)
            spectral = F.softmax(self.spectral_net(one), dim=-1) * self.solar_constant  # [n_ch]
            self.register_buffer('spectral_per_channel', spectral.detach().contiguous())

            mu_diffuse = torch.sigmoid(self.mu_diffuse_net(one)).reshape(())
            # Sync once here (one-time cost) so that the per-batch
            # forward pass can pass a Python float (no tensor read).
            self._inv_mu_diffuse_scalar = float(1.0 / (mu_diffuse.item() + 1.0e-7))

            # Pre-compute W_eff_filter[n_channels, 8] from the loaded
            # OpticalDepth weights.  This is the only piece of optical
            # depth that depends solely on parameters and not on per-row
            # inputs; the per-row tau is computed inside the fused
            # optical+scattering Triton kernel from
            #     mass[b, k] * ke[b, k] * W_eff_filter[c, k].
            od = self.optical_depth_net.module
            n_ch = self.n_channel

            # exp(W) for each gas, shape [n_ch]
            exp_w = torch.zeros(n_ch, 8, dtype=torch.float32, device=self.device)
            exp_w[:, 0] = torch.exp(od.net_lw .weight.reshape(-1))
            exp_w[:, 1] = torch.exp(od.net_iw .weight.reshape(-1))
            exp_w[:, 2] = torch.exp(od.net_h2o.weight.reshape(-1))
            exp_w[:, 3] = torch.exp(od.net_o3 .weight.reshape(-1))
            exp_w[:, 4] = torch.exp(od.net_co2.weight.reshape(-1))
            exp_w[:, 5] = torch.exp(od.net_o2 .weight.reshape(-1))
            exp_w[:, 6] = torch.exp(od.net_n2o.weight.reshape(-1))
            exp_w[:, 7] = torch.exp(od.net_ch4.weight.reshape(-1))

            # Apply the per-gas channel filter (clouds have no filter).
            # exp_w * filter is the only thing the Triton kernel needs.
            w_eff_filter = exp_w.clone()
            w_eff_filter[:, 2] *= od.filter_h2o
            w_eff_filter[:, 3] *= od.filter_o3
            w_eff_filter[:, 4] *= od.filter_co2
            w_eff_filter[:, 5] *= od.filter_o2
            w_eff_filter[:, 6] *= od.filter_n2o
            w_eff_filter[:, 7] *= od.filter_ch4
            self.register_buffer('w_eff_filter', w_eff_filter.contiguous())

            # Pre-pack ke MLP weights for fused ke+scattering kernel.
            # Layout per MLP (71 FP32 scalars):
            #   W0.T [2,6] + b0 [6] + W1.T [6,4] + b1 [4] +
            #   W2.T [4,4] + b2 [4] + W3.T [4,1] + b3 [1]
            # Six MLPs packed sequentially: total 426 scalars.
            if USE_FKE_SCATTERING:
                ke_mlps = [od.net_ke_h2o, od.net_ke_o3, od.net_ke_co2,
                           od.net_ke_o2, od.net_ke_n2o, od.net_ke_ch4]
                parts = []
                for mlp in ke_mlps:
                    parts.append(mlp.hidden[0].weight.T.contiguous().flatten())
                    parts.append(mlp.hidden[0].bias.detach())
                    parts.append(mlp.hidden[1].weight.T.contiguous().flatten())
                    parts.append(mlp.hidden[1].bias.detach())
                    parts.append(mlp.hidden[2].weight.T.contiguous().flatten())
                    parts.append(mlp.hidden[2].bias.detach())
                    parts.append(mlp.output.weight.T.contiguous().flatten())
                    parts.append(mlp.output.bias.detach())
                self.register_buffer('ke_weights_packed',
                                     torch.cat(parts).contiguous())

    @torch.compile(options={"triton.persistent_reductions": True})
    def _compute_ke(self, t_p_flat):
        """Run the six small ke MLPs (h2o, o3, co2, o2, n2o, ch4) with
        torch.compile for fusion, and return their per-row sigmoids
        stacked along the constituent axis.

        t_p_flat: [B, 2]   (temperature, pressure per sample-layer)
        returns:  [B, 6]
        """
        od = self.optical_depth_net.module
        ke_h2o = torch.sigmoid(od.net_ke_h2o(t_p_flat))
        ke_o3  = torch.sigmoid(od.net_ke_o3 (t_p_flat))
        ke_co2 = torch.sigmoid(od.net_ke_co2(t_p_flat))
        ke_o2  = torch.sigmoid(od.net_ke_o2 (t_p_flat))
        ke_n2o = torch.sigmoid(od.net_ke_n2o(t_p_flat))
        ke_ch4 = torch.sigmoid(od.net_ke_ch4(t_p_flat))
        return torch.cat([ke_h2o, ke_o3, ke_co2, ke_o2, ke_n2o, ke_ch4], dim=-1)

    def forward(self, x):
        x_layers, x_surface, _, _, _, = x

        n_examples, n_layers, _ = x_layers.shape
        B = n_examples * n_layers

        # Flatten the (sample, layer) axis once.  Both temperature/
        # pressure and constituent mass need this layout for the fused
        # optical+scattering kernel.
        temperature_pressure = x_layers[:, :, 0:2].reshape(B, 2)
        constituent_mass     = x_layers[:, :, 2:10].reshape(B, 8).contiguous()

        mu_direct = x_surface[:, 0]   # [n_examples]

        mu_dir_flat = mu_direct.unsqueeze(1).expand(n_examples, n_layers).reshape(B).contiguous()

        if TIMING_ENABLED:
            global t_optical_depth, t_scattering

        if USE_FKE_SCATTERING:
            # ---- 1+2. Fused ke+scattering (ke computed inline) ----
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                _t0 = time.time()
            tp_flat = temperature_pressure.contiguous()
            layers = self.scattering_net.module.forward_fke(
                constituent_mass, tp_flat, self.w_eff_filter, mu_dir_flat,
                self._inv_mu_diffuse_scalar, self.ke_weights_packed,
                n_examples, n_layers)
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_scattering += time.time() - _t0
        else:
            # ---- 1. Optical depth (ke MLPs only) ----
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                _t0 = time.time()
            ke = self._compute_ke(temperature_pressure)   # [B, 6]
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_optical_depth += time.time() - _t0

            # ---- 2. Scattering + remaining optical-depth math (fused) ----
            if TIMING_ENABLED:
                _t0 = time.time()
            layers = self.scattering_net.module(
                constituent_mass, ke, self.w_eff_filter, mu_dir_flat,
                self._inv_mu_diffuse_scalar, n_examples, n_layers)
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_scattering += time.time() - _t0

        if TIMING_ENABLED:
            global t_multireflection, t_input_flux, t_propagation

        if USE_FUSED_MULTIREF_PROP:
            # ---- 3+4+5. Fused multireflection + propagation ----
            if TIMING_ENABLED:
                _t0 = time.time()
            flux_direct = self.spectral_per_channel.unsqueeze(0) * mu_direct.unsqueeze(1)
            flux_diffuse = torch.zeros_like(flux_direct)
            flux = self.fused_multiref_prop(
                layers, x_surface, [flux_direct, flux_diffuse])
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_multireflection += time.time() - _t0

            (flux_down_direct, flux_down_diffuse, flux_up_diffuse,
             flux_absorbed) = flux
        else:
            # ---- 3. Multireflection (fused Triton kernel) ----
            if TIMING_ENABLED:
                _t0 = time.time()
            multireflected_layers, upward_reflection_toa = \
                self.multireflection_net((layers, x_surface,))
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_multireflection += time.time() - _t0

            # ---- 4. Build input flux ----
            if TIMING_ENABLED:
                _t0 = time.time()
            # flux_direct[i, c] = spectral_per_channel[c] * mu_direct[i]
            flux_direct = self.spectral_per_channel.unsqueeze(0) * mu_direct.unsqueeze(1)
            flux_diffuse = torch.zeros_like(flux_direct)
            input_flux = [flux_direct, flux_diffuse]
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_input_flux += time.time() - _t0

            # ---- 5. Propagation (fused Triton kernel) ----
            if TIMING_ENABLED:
                _t0 = time.time()
            flux = self.propagation_net((multireflected_layers,
                                        upward_reflection_toa,
                                        input_flux))
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_propagation += time.time() - _t0

            (flux_down_direct, flux_down_diffuse, flux_up_diffuse,
             flux_absorbed) = flux

        return [flux_down_direct, flux_down_diffuse, flux_up_diffuse, flux_absorbed]


# ---------------------------------------------------------------------------
# GPU-resident dataset and dataloader.
#
# `RTDataSet` lazily reads each month's netCDF the first time the worker
# touches an index in that month, which forces single-worker DataLoader
# usage and stalls the GPU on disk I/O.  For inference the entire year
# fits comfortably in L4 memory (~600 MB), so we read every month-file
# once up-front, concatenate them, and upload the result to the GPU.
# After that, batches are zero-copy slices of the GPU tensors and the
# host loop has no I/O on the critical path.
# ---------------------------------------------------------------------------
class GPUResidentDataset:
    """All-in-memory, GPU-resident replacement for `RTDataSet`.

    Loads each input file via `data_generation.load_data` (so the same
    NaN checks, normalization, daylight selection, and clear-sky logic
    apply), concatenates the per-file tensors along the sample axis,
    and uploads them to the target device once.  After construction the
    object is purely a container of GPU tensors.
    """

    def __init__(self, input_files, is_clear_sky, device,
                 default_float_type=torch.float32):
        x_layers_chunks      = []
        x_surface_chunks     = []
        delta_pressure_chunks = []
        y_chunks             = []
        sites_chunks         = []

        for file_index, path in enumerate(input_files):
            ds = xr.open_dataset(path)
            try:
                x_layers, x_surface, delta_pressure, y, sites = \
                    data_generation.load_data(
                        ds, file_index, is_clear_sky=is_clear_sky,
                        default_float_type=default_float_type)
            finally:
                ds.close()
            x_layers_chunks.append(x_layers)
            x_surface_chunks.append(x_surface)
            delta_pressure_chunks.append(delta_pressure)
            y_chunks.append(y)
            sites_chunks.append(sites)

        # Concatenate on CPU then move to GPU in one shot per tensor —
        # this avoids 12 separate H2D transfers and minimizes the
        # number of `cudaMalloc` calls.
        self.x_layers       = torch.cat(x_layers_chunks,       dim=0).to(device, non_blocking=True)
        self.x_surface      = torch.cat(x_surface_chunks,      dim=0).to(device, non_blocking=True)
        self.delta_pressure = torch.cat(delta_pressure_chunks, dim=0).to(device, non_blocking=True)
        self.y              = torch.cat(y_chunks,              dim=0).to(device, non_blocking=True)
        self.sites          = torch.cat(sites_chunks,          dim=0).to(device, non_blocking=True)

        self.n = self.x_layers.shape[0]
        torch.cuda.synchronize()

    def __len__(self):
        return self.n

    def free(self):
        del self.x_layers, self.x_surface, self.delta_pressure, self.y, self.sites
        torch.cuda.empty_cache()


class GPUDataLoader:
    """Drop-in replacement for `torch.utils.data.DataLoader` over a
    `GPUResidentDataset`.  Each yielded batch is a tuple of GPU tensor
    slices — no host transfer, no copies, no worker processes.

    The trailing partial batch is PADDED to `batch_size` by wrapping
    around to the beginning of the dataset, so every batch has the
    same size and Triton's autotune cache (keyed on B_total) stays
    warm.  Each iteration yields `(data_tuple, n_valid)` where
    `n_valid` is the number of real (non-padded) samples in the batch
    (equal to `batch_size` for full batches).  Consumers should run
    the model on the full padded batch (for a constant shape) and
    then slice outputs to `[:n_valid]` before computing metrics.
    """

    def __init__(self, dataset, batch_size):
        self.dataset = dataset
        self.batch_size = batch_size

    def __len__(self):
        return (self.dataset.n + self.batch_size - 1) // self.batch_size

    def __iter__(self):
        ds = self.dataset
        bs = self.batch_size
        n = ds.n
        for i in range(0, n, bs):
            if i + bs <= n:
                # Full batch — slice directly
                data = (ds.x_layers[i:i+bs],
                        ds.x_surface[i:i+bs],
                        ds.delta_pressure[i:i+bs],
                        ds.y[i:i+bs],
                        ds.sites[i:i+bs])
                yield data, bs
            else:
                # Partial batch — pad by wrapping around to the start
                n_valid = n - i
                n_pad = bs - n_valid
                data = (torch.cat([ds.x_layers[i:n], ds.x_layers[:n_pad]]),
                        torch.cat([ds.x_surface[i:n], ds.x_surface[:n_pad]]),
                        torch.cat([ds.delta_pressure[i:n], ds.delta_pressure[:n_pad]]),
                        torch.cat([ds.y[i:n], ds.y[:n_pad]]),
                        torch.cat([ds.sites[i:n], ds.sites[:n_pad]]))
                yield data, n_valid


# ---------------------------------------------------------------------------
# Fast test loop — no per-iteration syncs, GPU-resident loss accumulation.
# ---------------------------------------------------------------------------
def test_loop_fast(dataloader, model, loss_functions, loss_names,
                   loss_weights, device):
    model.eval()

    n_loss = len(loss_functions)
    num_batches = len(dataloader)
    # Loss accumulator lives on the GPU; copied to host once at the end.
    loss_acc = torch.zeros(n_loss, device=device, dtype=torch.float32)

    _reset_stage_timers()
    global t_data_to_gpu, t_loss

    # `t_compute` is the GPU-only time, matching original's `t_delt`.  It
    # syncs around the model's computation (and loss accumulation) but
    # NOT around the data-loading wait, so it isolates the work that
    # actually runs on the GPU from any host-side I/O stalls.
    t_compute = 0.0

    torch.cuda.synchronize()
    t_start = time.time()
    with torch.inference_mode():
        for data, n_valid in dataloader:
            if TIMING_ENABLED:
                _t0 = time.time()
            data = [x.to(device, non_blocking=True) for x in data]
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_data_to_gpu += time.time() - _t0

            torch.cuda.synchronize()
            t_fwd0 = time.time()
            # Run model on full padded batch to keep B_total constant
            # (so Triton's autotune cache hits on every call).
            y_pred = model(data)

            if TIMING_ENABLED:
                _t0 = time.time()
            # Slice to valid rows only before computing loss (ignore
            # padded duplicates).  Full batches have n_valid == batch_size
            # so slicing is a no-op.
            if n_valid < data[0].shape[0]:
                data_v = [x[:n_valid] for x in data]
                y_pred_v = tuple(
                    p[:n_valid] if isinstance(p, torch.Tensor) else p
                    for p in y_pred)
            else:
                data_v = data
                y_pred_v = y_pred
            for i, loss_fn in enumerate(loss_functions):
                loss_acc[i] = loss_acc[i] + loss_fn(data_v, y_pred_v, loss_weights)
            if TIMING_ENABLED:
                torch.cuda.synchronize()
                t_loss += time.time() - _t0

            torch.cuda.synchronize()
            t_compute += time.time() - t_fwd0
    torch.cuda.synchronize()
    t_delta = time.time() - t_start

    loss = (loss_acc / num_batches).cpu().numpy()

    print("Test Error:")
    for i, value in enumerate(loss):
        print(f" {loss_names[i]}: {value:.4f}")
    print(f"Time evaluation (w/o data I/O)         = {t_compute:.4f} s")
    print(f"Time evaluation (incl. data I/O wait)  = {t_delta:.4f} s")
    if TIMING_ENABLED:
        _print_stage_timers()
    print("")

    return loss, t_delta


